SELECT p.BPRSHO_0 AS NomCourt,CONVERT(varchar(10),p.XDATREG_0,23) AS DateRegularite,
 a.BPAADDLIG_0 AS Adresse,a.CTY_0 AS Ville,a.TEL_0 AS Telephone,a.FAX_0 AS Fax,
 s.PTE_0 AS Paiement,s.BSGCOD_0 AS Categorie,s.ACCCOD_0 AS CodeComptable,
 s.VACBPR_0 AS RegimeTaxe,s.CUR_0 AS Devise,p.CRY_0 AS Pays,
 s.PURPRITYP_0 AS TypeMontant,
 CASE WHEN EXISTS(SELECT 1 FROM TEST.ATABZON z JOIN TEST.APLSTD l ON l.LANCHP_0=z.NOLIB_0
  WHERE z.CODFIC_0='BPSUPPLIER' AND z.CODZONE_0='PURPRITYP' AND l.LANNUM_0=s.PURPRITYP_0 AND l.LAN_0='FRA'
  AND (l.LANMES_0 LIKE '%TTC%' OR l.LANMES_0 LIKE '%Toutes taxes%')) THEN 'TTC' ELSE 'HT' END AS TypeLibelle
FROM OB.BPARTNER p JOIN OB.BPSUPPLIER s ON s.BPSNUM_0=p.BPRNUM_0
JOIN OB.BPADDRESS a ON a.BPANUM_0=p.BPRNUM_0 AND a.BPAADD_0=s.BPAADD_0 AND a.BPATYP_0=1
WHERE p.BPRNUM_0='F103';
