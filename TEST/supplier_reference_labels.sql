SELECT 'Pays' AS kind,c.CRY_0 AS code,x.TEXTE_0 AS label FROM TEST.TABCOUNTRY c
JOIN TEST.ATEXTRA x ON x.CODFIC_0='TABCOUNTRY' AND x.ZONE_0='CRYDES' AND x.IDENT1_0=c.CRY_0 AND x.LANGUE_0='FRA'
UNION ALL
SELECT 'Paiement',p.PTE_0,x.TEXTE_0 FROM TEST.TABPAYTERM p
JOIN TEST.ATEXTRA x ON x.CODFIC_0='TABPAYTERM' AND x.ZONE_0='DESAXX' AND x.IDENT1_0=p.PTE_0 AND x.LANGUE_0='FRA';
